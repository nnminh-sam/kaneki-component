"use client";

import { useId, type ReactNode } from "react";
import { cn } from "../utils/cn";
import { useControllable } from "../utils/use-controllable";

export interface SegmentedOption {
  /** Value reported to `onChange`. */
  value: string;
  /** Segment text (also the accessible name). */
  label: ReactNode;
  /** Optional leading icon. */
  icon?: ReactNode;
  /** Disables this segment. */
  disabled?: boolean;
}

export type SegmentedSize = "sm" | "md" | "lg";

export interface SegmentedControlProps {
  /** Segments to render. */
  options: SegmentedOption[];
  /** Controlled selected value. */
  value?: string;
  /** Initial value when uncontrolled. */
  defaultValue?: string;
  /** Called with the newly selected value. */
  onChange?: (value: string) => void;
  /** `radio` (default): radiogroup of hidden native radios. `toggle`: aria-pressed buttons in a group. */
  mode?: "radio" | "toggle";
  /** Group label; visually hidden with `hideLabel`. */
  label?: ReactNode;
  /** Keep `label` for screen readers only. */
  hideLabel?: boolean;
  /** Accessible name when there is no `label`. */
  "aria-label"?: string;
  /** Native radio `name` (radio mode). Auto-generated by default. */
  name?: string;
  /** Segment height: sm 28px, md 32px, lg 40px (touch target). Default `md`. */
  size?: SegmentedSize;
  /** Stretch to the container width with equal segments. */
  fullWidth?: boolean;
  /** Disables the whole control. */
  disabled?: boolean;
  className?: string;
}

const sizeClasses: Record<SegmentedSize, string> = {
  sm: "h-7 px-2.5 text-xs gap-1",
  md: "h-8 px-3 text-sm gap-1.5",
  lg: "h-10 px-4 text-sm gap-2",
};

/** Single-choice segmented control with radio or toggle-button semantics. */
export function SegmentedControl({
  options,
  value,
  defaultValue,
  onChange,
  mode = "radio",
  label,
  hideLabel = false,
  "aria-label": ariaLabel,
  name,
  size = "md",
  fullWidth = false,
  disabled = false,
  className,
}: SegmentedControlProps) {
  const id = useId();
  const labelId = `${id}-label`;
  const groupName = name ?? `${id}-segmented`;
  const [selected, setSelected] = useControllable<string | undefined>(
    value,
    defaultValue,
    onChange as ((v: string | undefined) => void) | undefined
  );

  const segmentClass = (isSelected: boolean, isDisabled: boolean) =>
    cn(
      "relative inline-flex items-center justify-center whitespace-nowrap rounded-md font-medium transition-colors motion-reduce:transition-none",
      sizeClasses[size],
      fullWidth && "flex-1",
      isSelected ? "bg-surface text-fg shadow-xs" : "text-muted hover:text-fg",
      isDisabled ? "cursor-not-allowed opacity-50" : "cursor-pointer"
    );

  const content = (option: SegmentedOption) => (
    <>
      {option.icon && (
        <span aria-hidden="true" className="inline-flex shrink-0">
          {option.icon}
        </span>
      )}
      <span>{option.label}</span>
    </>
  );

  return (
    <div className={cn("flex flex-col gap-1.5", fullWidth ? "w-full" : "items-start", className)}>
      {label && (
        <span id={labelId} className={hideLabel ? "sr-only" : "text-xs font-semibold text-fg"}>
          {label}
        </span>
      )}
      <div
        role={mode === "radio" ? "radiogroup" : "group"}
        aria-labelledby={label ? labelId : undefined}
        aria-label={label ? undefined : ariaLabel}
        aria-disabled={disabled || undefined}
        className={cn(
          "inline-flex items-center gap-0.5 rounded-lg border border-border bg-surface-subtle p-0.5",
          fullWidth && "flex w-full"
        )}
      >
        {options.map((option) => {
          const isSelected = selected === option.value;
          const isDisabled = disabled || !!option.disabled;
          if (mode === "toggle") {
            return (
              <button
                key={option.value}
                type="button"
                aria-pressed={isSelected}
                disabled={isDisabled}
                onClick={() => {
                  if (!isSelected) setSelected(option.value);
                }}
                className={cn(
                  segmentClass(isSelected, isDisabled),
                  "focus-visible:outline-none focus-visible:ring-2 focus-visible:ring-accent"
                )}
              >
                {content(option)}
              </button>
            );
          }
          return (
            <label
              key={option.value}
              className={cn(
                segmentClass(isSelected, isDisabled),
                "has-[:focus-visible]:ring-2 has-[:focus-visible]:ring-accent"
              )}
            >
              <input
                type="radio"
                className="sr-only"
                name={groupName}
                value={option.value}
                checked={isSelected}
                disabled={isDisabled}
                onChange={() => setSelected(option.value)}
              />
              {content(option)}
            </label>
          );
        })}
      </div>
    </div>
  );
}
